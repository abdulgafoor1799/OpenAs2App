-- V1: partnership store for org.openas2.partner.DbPartnershipFactory (PostgreSQL) + 4.15 tracking columns.
-- Run against the openas2 database as a superuser / RDS master user:
--   psql -v ON_ERROR_STOP=1 -d openas2 -f V1__partnership_tables.sql
-- Idempotent. Role passwords are NOT set here: set them afterwards with \password <role>.
--
-- Ownership model:
--   as2_config_admin  owns the config tables; used by migrations and the EDIPLUG backend (single writer)
--   openas2           OpenAS2 runtime; read-only on config tables, read/write on msg_metadata

BEGIN;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'as2_config_admin') THEN
        CREATE ROLE as2_config_admin LOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'openas2') THEN
        CREATE ROLE openas2 LOGIN;
    END IF;
END
$$;

GRANT CONNECT ON DATABASE openas2 TO as2_config_admin, openas2;
GRANT USAGE ON SCHEMA public TO as2_config_admin, openas2;
GRANT CREATE ON SCHEMA public TO as2_config_admin;

-- Table and column names are unquoted so they match the unquoted upper case SQL in DbPartnershipFactory.
CREATE TABLE IF NOT EXISTS partner
(
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS partner_name_unique ON partner (name);

CREATE TABLE IF NOT EXISTS partner_attribute
(
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_id      integer NOT NULL REFERENCES partner (id) ON DELETE CASCADE,
    attribute_name  varchar(255) NOT NULL,
    attribute_value varchar(4000)
);
CREATE UNIQUE INDEX IF NOT EXISTS partner_attribute_unique ON partner_attribute (partner_id, attribute_name);

CREATE TABLE IF NOT EXISTS partnership
(
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                varchar(255) NOT NULL,
    sender_partner_id   integer NOT NULL REFERENCES partner (id),
    receiver_partner_id integer NOT NULL REFERENCES partner (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS partnership_name_unique ON partnership (name);

CREATE TABLE IF NOT EXISTS partnership_attribute
(
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partnership_id  integer NOT NULL REFERENCES partnership (id) ON DELETE CASCADE,
    category        varchar(20) NOT NULL DEFAULT 'attribute'
                    CHECK (category IN ('attribute', 'sender', 'receiver', 'pollerConfig')),
    attribute_name  varchar(255) NOT NULL,
    attribute_value varchar(4000)
);
CREATE UNIQUE INDEX IF NOT EXISTS partnership_attribute_unique
    ON partnership_attribute (partnership_id, category, attribute_name);

ALTER TABLE partner OWNER TO as2_config_admin;
ALTER TABLE partner_attribute OWNER TO as2_config_admin;
ALTER TABLE partnership OWNER TO as2_config_admin;
ALTER TABLE partnership_attribute OWNER TO as2_config_admin;

REVOKE ALL ON partner, partner_attribute, partnership, partnership_attribute FROM PUBLIC;
GRANT SELECT ON partner, partner_attribute, partnership, partnership_attribute TO openas2;

-- Message tracking columns added between 4.8 and 4.15 (sent_file_name, mdn_file_path).
ALTER TABLE IF EXISTS msg_metadata ADD COLUMN IF NOT EXISTS sent_file_name varchar(255);
ALTER TABLE IF EXISTS msg_metadata ADD COLUMN IF NOT EXISTS mdn_file_path text;

COMMIT;
